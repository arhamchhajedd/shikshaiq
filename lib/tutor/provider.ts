/**
 * Socratic AI Tutor Provider Abstraction
 * Supports Google Gemini, OpenAI, or reports unconfigured state honestly.
 * All API keys are kept strictly server-side.
 */

import { TutorLanguage } from "@/types/tutor";

export interface ProviderChatMessage {
  role: "user" | "assistant";
  content: string;
}

export interface ProviderGenerateParams {
  systemPrompt: string;
  userMessage: string;
  conversationHistory: ProviderChatMessage[];
  language: TutorLanguage;
}

export interface ProviderGenerateResult {
  text: string;
}

export interface AITutorProvider {
  isConfigured(): boolean;
  getProviderName(): string;
  generateResponse(params: ProviderGenerateParams): Promise<ProviderGenerateResult>;
}

/**
 * Null Provider: Used when no valid LLM provider keys are supplied in environment variables.
 */
export class NullTutorProvider implements AITutorProvider {
  isConfigured(): boolean {
    return false;
  }

  getProviderName(): string {
    return "unconfigured";
  }

  async generateResponse(_params?: ProviderGenerateParams): Promise<ProviderGenerateResult> {
    void _params;
    throw new Error(
      "AI Tutor provider is not configured. Please supply GEMINI_API_KEY or OPENAI_API_KEY in your server environment."
    );
  }
}

/**
 * Google Gemini Provider
 */
export class GeminiTutorProvider implements AITutorProvider {
  private apiKey: string;
  private model: string;

  constructor(apiKey: string, model: string = "gemini-1.5-flash") {
    this.apiKey = apiKey;
    this.model = model;
  }

  isConfigured(): boolean {
    return Boolean(this.apiKey && this.apiKey.trim().length > 0);
  }

  getProviderName(): string {
    return `google-gemini (${this.model})`;
  }

  async generateResponse(params: ProviderGenerateParams): Promise<ProviderGenerateResult> {
    const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${encodeURIComponent(
      this.model
    )}:generateContent?key=${encodeURIComponent(this.apiKey)}`;

    // Format contents for Gemini: system_instruction + conversation history + current user message
    const contents: Array<{ role: "user" | "model"; parts: Array<{ text: string }> }> = [];

    for (const msg of params.conversationHistory) {
      contents.push({
        role: msg.role === "assistant" ? "model" : "user",
        parts: [{ text: msg.content }],
      });
    }

    contents.push({
      role: "user",
      parts: [{ text: params.userMessage }],
    });

    const requestBody = {
      system_instruction: {
        parts: [{ text: params.systemPrompt }],
      },
      contents,
      generationConfig: {
        temperature: 0.4,
        maxOutputTokens: 600,
        topP: 0.9,
      },
    };

    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 15000);

    try {
      const response = await fetch(endpoint, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
        },
        body: JSON.stringify(requestBody),
        signal: controller.signal,
      });

      if (!response.ok) {
        const errorText = await response.text().catch(() => "");
        throw new Error(`Gemini API error (${response.status}): ${errorText.slice(0, 150)}`);
      }

      const data = await response.json();
      const candidate = data.candidates?.[0];
      const partText = candidate?.content?.parts?.[0]?.text;

      if (!partText) {
        throw new Error("No text response generated by Gemini model.");
      }

      return { text: partText.trim() };
    } finally {
      clearTimeout(timeout);
    }
  }
}

/**
 * OpenAI Provider
 */
export class OpenAITutorProvider implements AITutorProvider {
  private apiKey: string;
  private model: string;

  constructor(apiKey: string, model: string = "gpt-4o-mini") {
    this.apiKey = apiKey;
    this.model = model;
  }

  isConfigured(): boolean {
    return Boolean(this.apiKey && this.apiKey.trim().length > 0);
  }

  getProviderName(): string {
    return `openai (${this.model})`;
  }

  async generateResponse(params: ProviderGenerateParams): Promise<ProviderGenerateResult> {
    const endpoint = "https://api.openai.com/v1/chat/completions";

    const messages: Array<{ role: "system" | "user" | "assistant"; content: string }> = [
      { role: "system", content: params.systemPrompt },
    ];

    for (const msg of params.conversationHistory) {
      messages.push({
        role: msg.role === "assistant" ? "assistant" : "user",
        content: msg.content,
      });
    }

    messages.push({
      role: "user",
      content: params.userMessage,
    });

    const requestBody = {
      model: this.model,
      messages,
      temperature: 0.4,
      max_tokens: 600,
    };

    const controller = new AbortController();
    const timeout = setTimeout(() => controller.abort(), 15000);

    try {
      const response = await fetch(endpoint, {
        method: "POST",
        headers: {
          "Content-Type": "application/json",
          Authorization: `Bearer ${this.apiKey}`,
        },
        body: JSON.stringify(requestBody),
        signal: controller.signal,
      });

      if (!response.ok) {
        const errorText = await response.text().catch(() => "");
        throw new Error(`OpenAI API error (${response.status}): ${errorText.slice(0, 150)}`);
      }

      const data = await response.json();
      const content = data.choices?.[0]?.message?.content;

      if (!content) {
        throw new Error("No message content returned by OpenAI.");
      }

      return { text: content.trim() };
    } finally {
      clearTimeout(timeout);
    }
  }
}

/**
 * Factory to retrieve the active configured AI Tutor provider.
 * Looks for server-side environment variables.
 */
export function getTutorProvider(): AITutorProvider {
  const preferredProvider = process.env.AI_PROVIDER?.toLowerCase().trim();
  const geminiKey = process.env.GEMINI_API_KEY?.trim();
  const openAiKey = process.env.OPENAI_API_KEY?.trim();
  const customModel = process.env.AI_MODEL?.trim();

  if (preferredProvider === "openai" && openAiKey) {
    return new OpenAITutorProvider(openAiKey, customModel || "gpt-4o-mini");
  }

  if (preferredProvider === "gemini" && geminiKey) {
    return new GeminiTutorProvider(geminiKey, customModel || "gemini-1.5-flash");
  }

  // Auto-detection
  if (geminiKey) {
    return new GeminiTutorProvider(geminiKey, customModel || "gemini-1.5-flash");
  }

  if (openAiKey) {
    return new OpenAITutorProvider(openAiKey, customModel || "gpt-4o-mini");
  }

  return new NullTutorProvider();
}
